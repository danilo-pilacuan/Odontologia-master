    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
            // TODO add your handling code here:
            try
        {
            String buscar=txtBuscar.getText();
            if(cbxCriterio.getSelectedIndex()==0)
            {
                if(controlClinica.obtenerPaciente(buscar)!=null)
                {
                   listaP=new ArrayList<Paciente>();
                   listaP.add(controlClinica.obtenerPaciente(buscar));
                }
                else
                {
                    listaP=new ArrayList<Paciente>();
                }
            }
            else if(cbxCriterio.getSelectedIndex()==1)
            {
                listaP=controlClinica.obtenerPacientesPorNombres(buscar);
            }
            else
            {
                listaP=controlClinica.obtenerPacientesPorApellidos(buscar);
            }
            llenarTabla();
        }
        catch(Exception e)
        {
            System.out.println(e.toString());
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        try
        {
            if(pacienteSeleccionado!=null)
            {
                int idCita;
                Paciente pacienteCita;
                Date fechaCita;
                String horaCita;
                String razon;
                String procedimiento;
                float costo;
                boolean asistencia;

                idCita=0;
                pacienteCita=pacienteSeleccionado;
                
                fechaCita=dtpFecha.getDate();
                if(fechaCita.getTime()>Calendar.getInstance().getTime().getTime())
                {
                    horaCita=(String)cbxHora.getSelectedItem();
                    razon=txtRazon.getText();
                    procedimiento=txtProcedimiento.getText();
                    costo=Float.parseFloat(txtCosto.getText());
                    if(cbxAsistencia.getSelectedIndex()==0)
                        asistencia=true;
                    else
                        asistencia=false;
                    Cita nuevaCita= new Cita(idCita,pacienteCita,fechaCita,horaCita,razon,procedimiento,costo,asistencia);
                    CitaDAO.agregarCita(nuevaCita);
                    JOptionPane.showMessageDialog(null,"Cita registrada con éxito","Éxito",JOptionPane.INFORMATION_MESSAGE);
                }
                else
                {
                    JOptionPane.showMessageDialog(null,"La fecha no puede ser menor que la actual","Éxito",JOptionPane.INFORMATION_MESSAGE);
                }
            }
            else
            {
                JOptionPane.showMessageDialog(null,"Seleccione un paciente primero","Error",JOptionPane.INFORMATION_MESSAGE);
            }
                        
        }
        catch(Exception ex)
        {
            System.out.println(ex.toString());
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed


