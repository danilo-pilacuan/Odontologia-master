    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        try
        {
            String buscar=txtBuscar.getText();
            if(cbxCriterio.getSelectedIndex()==0)
            {
                if(controlClinica.obtenerPaciente(buscar)!=null)
                {
                   listaCitas=CitaDAO.obtenerCitasPorCedula(controlClinica.obtenerPaciente(buscar).getCedula());
                }
                else
                {
                    listaCitas=new ArrayList<>();
                }
            }
            else if(cbxCriterio.getSelectedIndex()==1)
            {
                listaCitas=CitaDAO.obtenerCitasPorNombres(buscar);
            }
            else
            {
                listaCitas=CitaDAO.obtenerCitasPorApellidos(buscar);
            }
            ultimaBusqueda=0;
            llenarTabla();
        }
        catch(Exception e)
        {
            System.out.println(e.toString());
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        if(citaEliminar!=null)
        {
            if(CitaDAO.eliminarCita(idCitaEliminar)==1)
            {
                JOptionPane.showMessageDialog(null,"Cita eliminada con éxito","Éxito",JOptionPane.INFORMATION_MESSAGE);
                
                if(ultimaBusqueda==0)
                {
                    try
                    {
                        String buscar=txtBuscar.getText();
                        if(cbxCriterio.getSelectedIndex()==0)
                        {
                            if(controlClinica.obtenerPaciente(buscar)!=null)
                            {
                               listaCitas=CitaDAO.obtenerCitasPorCedula(controlClinica.obtenerPaciente(buscar).getCedula());
                            }
                            else
                            {
                                listaCitas=new ArrayList<>();
                            }
                        }
                        else if(cbxCriterio.getSelectedIndex()==1)
                        {
                            listaCitas=CitaDAO.obtenerCitasPorNombres(buscar);
                        }
                        else
                        {
                            listaCitas=CitaDAO.obtenerCitasPorApellidos(buscar);
                        }
                        ultimaBusqueda=0;
                        llenarTabla();
                    }
                    catch(Exception e)
                    {
                        System.out.println(e.toString());
                    }
                }
                else if(ultimaBusqueda==1)
                {
                    try
                    {
                        Date fechaBuscar=dtpBuscarPorFecha.getDate();
                        if(fechaBuscar!=null)
                        {
                            listaCitas=CitaDAO.obtenerCitasPorFecha(fechaBuscar);
                        }
                        ultimaBusqueda=1;
                        llenarTabla();
                    }
                    catch(Exception e)
                    {
                        System.out.println(e.toString());
                    }
                }
                
                citaEliminar=null;
            }
            else
            {
                JOptionPane.showMessageDialog(null,"No se pudo eliminar la cita","Error",JOptionPane.INFORMATION_MESSAGE);
            }
            
        }
        else
        {
            JOptionPane.showMessageDialog(null,"Selecciona una cita a eliminar","Error",JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

