    private void btnBuscarPorCedulaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarPorCedulaActionPerformed
        // TODO add your handling code here:
        try
        {
            String buscar=txtBuscar.getText();
            if(cbxCriterio.getSelectedIndex()==0)
            {
                if(controlClinica.obtenerPaciente(buscar)!=null)
                {
                   listaCitas=CitaDAO.obtenerCitasPorCedula(controlClinica.obtenerPaciente(buscar).getCedula());
                }
                else
                {
                    listaCitas=new ArrayList<>();
                }
            }
            else if(cbxCriterio.getSelectedIndex()==1)
            {
                listaCitas=CitaDAO.obtenerCitasPorNombres(buscar);
            }
            else
            {
                listaCitas=CitaDAO.obtenerCitasPorApellidos(buscar);
            }
            llenarTabla();
        }
        catch(Exception e)
        {
            System.out.println(e.toString());
        }
    }//GEN-LAST:event_btnBuscarPorCedulaActionPerformed


