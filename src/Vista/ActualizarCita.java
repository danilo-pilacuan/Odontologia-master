    public ListSelectionListener setListener() {
        return new ListSelectionListener() {
            public void valueChanged(ListSelectionEvent event) {
                try {
                    if (Integer.parseInt(tablaDatos.getValueAt(tablaDatos.getSelectedRow(), 0).toString()) >= 0) {

                        idCitaActualizar = Integer.parseInt(tablaDatos.getValueAt(tablaDatos.getSelectedRow(), 0).toString());
                        //System.out.println(idCitaEliminar);
                        citaActualizar = CitaDAO.obtenerCitaPorId(idCitaActualizar);
                        if (citaActualizar != null) {
                            dtpFechaActualizada.setDate(citaActualizar.getFechaCita());
                            for (int i = 0; i < cbxHora.getItemCount(); i++) {
                                if (cbxHora.getItemAt(0).equals(citaActualizar.getHoraCita())) {
                                    cbxHora.setSelectedIndex(i);
                                    break;
                                }
                            }
                            txtRazon.setText(citaActualizar.getRazon());
                            txtProcedimiento.setText(citaActualizar.getProcedimiento());
                            if (citaActualizar.getAsistencia()) {
                                cbxAsistencia.setSelectedIndex(0);
                            } else {
                                cbxAsistencia.setSelectedIndex(1);
                            }
                        }
                    }

                } catch (Exception ex) {
                    //System.out.println(ex);
                }
            }
        };
    }

    public void llenarTabla() {
        try {
            DefaultTableModel modelo = (DefaultTableModel) tablaDatos.getModel();
            modelo.setRowCount(0);
            if (listaCitas != null) {
                for (Cita auxC : listaCitas) {
                    modelo.addRow(new Object[]{auxC.getIdCita(), auxC.getPacienteCita().getCedula(), auxC.getPacienteCita().getNombres(),
                        auxC.getPacienteCita().getApellidos(), auxC.getFechaCita().toString(), auxC.getHoraCita(), auxC.getRazon(), auxC.getCosto()});
                }
            }
        } catch (Exception ex) {
            //System.out.println(ex);
        }
    }

