    private void btnCargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarActionPerformed
        // TODO add your handling code here:
        try
        {
            JFileChooser fileChooser = new JFileChooser();
            fileChooser.setCurrentDirectory(new File(System.getProperty("user.home")));
            int result = fileChooser.showOpenDialog(this);
            if(result==JFileChooser.APPROVE_OPTION)
            {
                imgSel = fileChooser.getSelectedFile();
                lblImagen.setIcon(new javax.swing.ImageIcon(imgSel.getAbsolutePath())); 
            }
            
        }
        catch(Exception ex)
        {
            
        }
    }//GEN-LAST:event_btnCargarActionPerformed

    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        try
        {
            if(!txtDescripcion.getText().equals(""))
            {
                String descripcion=txtDescripcion.getText();
                if(imgSel!=null)
                {                    
                    try
                    {
                        Path directorioRelativoActual = Paths.get("");
                        String dirTrabajo = directorioRelativoActual.toAbsolutePath().toString();
                        //System.out.println("Current relative path is: " + dirTrabajo);
                        Path sourceFile = Paths.get(imgSel.getAbsolutePath());
                        Path targetFile = Paths.get(dirTrabajo+"\\imgs\\radio\\"+pacienteSel.getCedula()+"-"+nombreEnFecha+".jpg");
                        String ubicacion="\\imgs\\radio\\"+pacienteSel.getCedula()+"-"+nombreEnFecha+".jpg";
                        try {

                            Files.copy(sourceFile, targetFile,
                                StandardCopyOption.REPLACE_EXISTING);
                            Radiografia radioNueva=new Radiografia(1,pacienteSel.getCedula(),ubicacion,descripcion,Calendar.getInstance().getTime());
                            RadiografiaDAO.agregarRadiografia(radioNueva);
                            frmPadre.llenarTablaR();
                            exitoImg=true;
                            JOptionPane.showMessageDialog(null,"Radiografia agregada con éxito","Éxito",JOptionPane.INFORMATION_MESSAGE);
                            this.setVisible(false);
                            
                            //System.out.println("Exito");

                        } catch (IOException ex) {
                            System.out.println(ex.toString());
                            System.err.format("I/O Error when copying file");
}
                    }
                    catch(Exception ex)
                    {
                        System.out.println(ex.toString());
                    }
                }
            }
            else
            {
                JOptionPane.showMessageDialog(null,"Ingrese una descripcion","Error",JOptionPane.INFORMATION_MESSAGE);
            }
        }
        catch(Exception ex)
        {
            System.out.println(ex.toString());
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

