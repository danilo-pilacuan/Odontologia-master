    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        //Date date = jDateChooser1.getDate();
        try
        {
            if(Calendar.getInstance().getTime().getTime()>dateFechaNac.getDate().getTime())
            {
                String cedula;
                String nombres;
                String apellidos;
                Date fechaNacimiento;
                String direccion;
                String telefono;
                String email;
                boolean estado;
                
                cedula=txtCedula.getText();
                nombres=txtNombres.getText();
                apellidos=txtApellidos.getText();
                fechaNacimiento=dateFechaNac.getDate();
                direccion=txtDireccion.getText();
                telefono=txtTelefono.getText();
                email=txtEmail.getText();
                if(cbxEstado.getSelectedIndex()==0)
                    estado=true;
                else
                    estado=false;
                Paciente nuevoP = new Paciente(cedula,nombres,apellidos,fechaNacimiento,direccion,telefono,email,estado);
                HistoriaClinica nuevaH = new HistoriaClinica(HistoriaClinicaDAO.getListaHistorias().size()+1,nuevoP,"","");
                if(controlClinica.crearPaciente(nuevoP)==1 && HistoriaClinicaDAO.agregarHistoriaClinica(nuevaH)==1)
                {
                    JOptionPane.showMessageDialog(null,"Paciente registrado con éxito","Éxito",JOptionPane.INFORMATION_MESSAGE);
                    txtCedula.setText("");
                    txtNombres.setText("");
                    txtApellidos.setText("");
                    dateFechaNac.setDate(Calendar.getInstance().getTime());
                    txtDireccion.setText("");
                    txtTelefono.setText("");
                    txtEmail.setText("");
                }
                else
                {
                    if(controlClinica.obtenerPaciente(cedula)!=null)
                        JOptionPane.showMessageDialog(null,"El usuario ya existe","Error",JOptionPane.INFORMATION_MESSAGE);
                    else
                        JOptionPane.showMessageDialog(null,"Revise los campos","Error",JOptionPane.INFORMATION_MESSAGE);
                }
            }
            
            
        }
        catch(Exception e)
        {
            System.out.println(e.toString());
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed


