    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        try {
            String buscar = txtBuscar.getText();
            if (cbxCriterio.getSelectedIndex() == 0) {
                if (controlClinica.obtenerPaciente(buscar) != null) {
                    listaCitas = CitaDAO.obtenerCitasPorCedula(controlClinica.obtenerPaciente(buscar).getCedula());
                } else {
                    listaCitas = new ArrayList<>();
                }
            } else if (cbxCriterio.getSelectedIndex() == 1) {
                listaCitas = CitaDAO.obtenerCitasPorNombres(buscar);
            } else {
                listaCitas = CitaDAO.obtenerCitasPorApellidos(buscar);
            }
            ultimaBusqueda = 0;
            llenarTabla();
        } catch (Exception e) {
            //System.out.println(e.toString());
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        try {
            if (citaActualizar != null) {
                int idCita;
                Paciente pacienteCita;
                Date fechaCita;
                String horaCita;
                String razon;
                String procedimiento;
                float costo;
                boolean asistencia;

                //idCita=0;
                //pacienteCita=pacienteSeleccionado;
                fechaCita = dtpFechaActualizada.getDate();
                if (fechaCita.getTime() > Calendar.getInstance().getTime().getTime()) {
                    horaCita = (String) cbxHora.getSelectedItem();
                    razon = txtRazon.getText();
                    procedimiento = txtProcedimiento.getText();
                    //costo=Float.parseFloat(txtCosto.getText());
                    if (cbxAsistencia.getSelectedIndex() == 0) {
                        asistencia = true;
                    } else {
                        asistencia = false;
                    }
                    //Cita nuevaCita= new Cita(idCita,pacienteCita,fechaCita,horaCita,razon,procedimiento,costo,asistencia);
                    //CitaDAO.agregarCita(nuevaCita);

                    citaActualizar.setFechaCita(fechaCita);
                    citaActualizar.setHoraCita(horaCita);
                    citaActualizar.setRazon(razon);
                    citaActualizar.setProcedimiento(procedimiento);
                    citaActualizar.setAsistencia(asistencia);
                    if (CitaDAO.actualizarCita(citaActualizar.getIdCita(), citaActualizar) == 1) {
                        if (ultimaBusqueda == 0) {
                            try {
                                String buscar = txtBuscar.getText();
                                if (cbxCriterio.getSelectedIndex() == 0) {
                                    if (controlClinica.obtenerPaciente(buscar) != null) {
                                        listaCitas = CitaDAO.obtenerCitasPorCedula(controlClinica.obtenerPaciente(buscar).getCedula());
                                    } else {
                                        listaCitas = new ArrayList<>();
                                    }
                                } else if (cbxCriterio.getSelectedIndex() == 1) {
                                    listaCitas = CitaDAO.obtenerCitasPorNombres(buscar);
                                } else {
                                    listaCitas = CitaDAO.obtenerCitasPorApellidos(buscar);
                                }
                                ultimaBusqueda = 0;
                                llenarTabla();
                            } catch (Exception e) {
                                //System.out.println(e.toString());
                            }
                        } else if (ultimaBusqueda == 1) {
                            try {
                                Date fechaBuscar = dtpBuscarPorFecha.getDate();
                                if (fechaBuscar != null) {
                                    listaCitas = CitaDAO.obtenerCitasPorFecha(fechaBuscar);
                                }
                                ultimaBusqueda = 1;
                                llenarTabla();
                            } catch (Exception e) {
                                //System.out.println(e.toString());
                            }
                        }
                        JOptionPane.showMessageDialog(null, "Cita actualizada con éxito", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                    } else {
                        JOptionPane.showMessageDialog(null, "No se pudo actualizar", "Error", JOptionPane.INFORMATION_MESSAGE);
                    }
                } else {
                    JOptionPane.showMessageDialog(null, "La fecha no puede ser menor que la actual", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                }
            } else {
                JOptionPane.showMessageDialog(null, "Seleccione una cita primero", "Error", JOptionPane.INFORMATION_MESSAGE);
            }

        } catch (Exception ex) {
            //System.out.println(ex.toString());
        }


    }//GEN-LAST:event_btnActualizarActionPerformed

